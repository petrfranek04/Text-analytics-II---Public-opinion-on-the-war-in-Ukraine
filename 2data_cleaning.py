import os
import re
import pandas as pd

def clean_scraped_data(df):
    """
    Cleans raw scraped Reddit records and tracks record counts across each filtering step.
    Produces two distinct text columns tailored for downstream NLP models:
      - 'text_sentiment': preserves punctuation (e.g., '!!!') and capitalization for VADER and RoBERTa.
      - 'text_topic': strips markdown formatting and Reddit mentions for BERTopic clustering.
    """
    # Dictionary tracking record counts at each stage of the filtering funnel
    stats = {"1_total_raw_records": len(df)}

    # Stage 1: Deduplication by unique Reddit record ID
    df = df.drop_duplicates(subset=["record_id"], keep="first").copy()
    stats["2_after_id_deduplication"] = len(df)

    # Stage 2: Removal of deleted accounts, removed content, and automated moderation bots
    df = df[~df["author_hash"].isin(["deleted_or_bot"])]
    df = df[~df["text"].isin(["[removed]", "[deleted]", ""])]

    # Regular expression matching standard automated moderator disclaimers
    bot_patterns = r"I am a bot|performed automatically|RemindMe!|submission statement"
    df = df[~df["text"].str.contains(bot_patterns, case=False, na=False)]
    stats["3_after_bot_and_deleted_removal"] = len(df)

    # Stage 3: Removal of quoted blocks ('>') and URLs for sentiment analysis.
    # Quoted lines represent opposing arguments cited by commenters before refuting them;
    # stripping them prevents sentiment models from scoring the quoted opponent's text.
    def clean_for_sentiment(text):
        text = re.sub(r"(?m)^>.*$", "", str(text))        # Removes markdown quote lines
        text = re.sub(r"http\S+|www\.\S+", "", text)      # Removes HTTP/HTTPS links
        return re.sub(r"\s+", " ", text).strip()          # Normalizes whitespace

    df["text_sentiment"] = df["text"].apply(clean_for_sentiment)

    # Stage 4: Deeper text normalization for topic modeling (strips subreddit/user tags and markdown symbols)
    def clean_for_bertopic(text):
        text = re.sub(r"/?[ru]/[A-Za-z0-9_-]+", "", text)
        text = re.sub(r"[\*\[\]\(\)~_`#]", " ", text)
        return re.sub(r"\s+", " ", text).strip()

    df["text_topic"] = df["text_sentiment"].apply(clean_for_bertopic)

    # Stage 5: Cross-post spam removal based on identical cleaned text
    df = df.drop_duplicates(subset=["text_sentiment"], keep="first")
    stats["4_after_spam_deduplication"] = len(df)

    # Stage 6: Minimum length filtering (excludes low-context replies shorter than 5 words)
    df["word_count"] = df["text_sentiment"].apply(lambda x: len(x.split()))
    df = df[df["word_count"] >= 5].copy()
    stats["5_final_clean_records"] = len(df)

    return df, pd.Series(stats, name="Record_Count")

if __name__ == "__main__":
    # Input checkpoint generated by 1reddit_scraper.py
    input_path = "data/raw/reddit_raw_checkpoint.csv"
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Input file '{input_path}' not found. Run 1reddit_scraper.py first.")

    df_raw_all = pd.read_csv(input_path)
    df_clean, funnel_table = clean_scraped_data(df_raw_all)

    print("=== DATA CLEANING FUNNEL ===")
    print(funnel_table.to_frame())

    # Exports the complete cleaned dataset locally (git-ignored; distributed to team members via Drive/Teams)
    os.makedirs("data/raw", exist_ok=True)
    df_clean.to_csv("data/raw/reddit_cleaned_full.csv", index=False)

    # Exports a 100-row anonymized sample without raw uncleaned text for the public GitHub repository
    os.makedirs("data/sample", exist_ok=True)
    df_sample = df_clean.drop(columns=["text"]).sample(n=min(100, len(df_clean)), random_state=42)
    df_sample.to_csv("data/sample/sample_anonymized.csv", index=False)

    print(f"\nFull cleaned dataset saved to 'data/raw/reddit_cleaned_full.csv' ({len(df_clean)} rows).")
    print("Anonymized 100-row GitHub sample saved to 'data/sample/sample_anonymized.csv'.")
    print("\nSample preview:")
